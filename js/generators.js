/* generators.js: byte-exact test file generation.
 * Every generator returns a Uint8Array. Where exact-size padding hits a
 * structural minimum (a handful of bytes for GIF/JPEG/PNG comment blocks),
 * the function gets as close as physically possible and the caller should
 * always read back blob.size rather than trust the request blindly, the
 * UI does this and surfaces the real achieved size.
 */
(function (root) {
  const isNode = typeof module !== "undefined" && !!module.exports;
  const U = isNode ? require("./utils.js") : root;
  const { crc32Final, concatBytes, u16le, u32le, u16be, u32be, textBytes, randomBytes } = U;

  function b64decode(str) {
    if (typeof atob === "function") {
      const bin = atob(str);
      const out = new Uint8Array(bin.length);
      for (let i = 0; i < bin.length; i++) out[i] = bin.charCodeAt(i);
      return out;
    }
    return new Uint8Array(Buffer.from(str, "base64"));
  }

  // ---------- TXT ----------
  function generateTxt(size, mode = "text") {
    if (mode === "random") return randomPrintable(size);
    if (mode === "blank") {
      const out = new Uint8Array(size);
      out.fill(0x20); // spaces, so it's still a "normal" text file
      return out;
    }
    const filler = "This is a test file generated by DevToolbox. ";
    const fillerBytes = textBytes(filler);
    const out = new Uint8Array(size);
    for (let i = 0; i < size; i++) out[i] = fillerBytes[i % fillerBytes.length];
    return out;
  }

  function randomPrintable(size) {
    const raw = randomBytes(size);
    const out = new Uint8Array(size);
    for (let i = 0; i < size; i++) out[i] = 0x20 + (raw[i] % 95); // printable ASCII range
    return out;
  }

  // ---------- BIN ----------
  function generateBin(size, mode = "random") {
    return randomBytes(size, mode);
  }

  // ---------- PDF ----------
  function generatePdf(size) {
    const header = textBytes("%PDF-1.4\n%\xE2\xE3\xCF\xD3\n");
    const content = "BT /F1 18 Tf 20 100 Td (Generated by DevToolbox) Tj ET";
    const contentBytes = textBytes(content);
    const obj1 = textBytes("1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n");
    const obj2 = textBytes("2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n");
    const obj3 = textBytes(
      "3 0 obj\n<< /Type /Page /Parent 2 0 R /MediaBox [0 0 200 200] " +
      "/Resources << /Font << /F1 5 0 R >> >> /Contents 4 0 R >>\nendobj\n"
    );
    const obj4 = textBytes(
      `4 0 obj\n<< /Length ${contentBytes.length} >>\nstream\n${content}\nendstream\nendobj\n`
    );
    const obj5 = textBytes("5 0 obj\n<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>\nendobj\n");

    const minComment = textBytes("%\n");
    const baseline =
      header.length + minComment.length + obj1.length + obj2.length + obj3.length +
      obj4.length + obj5.length + xrefTrailerLength(5);

    let commentBytes = minComment;
    let achievableMin = baseline;
    if (size > baseline) {
      const padLen = size - baseline; // extra bytes beyond the 2-byte minimum comment
      const fillerChar = "A";
      commentBytes = textBytes("%" + fillerChar.repeat(padLen) + "\n");
    }

    const objs = [obj1, obj2, obj3, obj4, obj5];
    let offset = header.length + commentBytes.length;
    const offsets = [];
    const objBytesList = [];
    for (const obj of objs) {
      offsets.push(offset);
      objBytesList.push(obj);
      offset += obj.length;
    }
    const xrefOffset = offset;

    let xref = "xref\n0 6\n0000000000 65535 f \n";
    for (const off of offsets) {
      xref += String(off).padStart(10, "0") + " 00000 n \n";
    }
    // startxref is padded to a fixed width so its byte length never depends
    // on the offset's magnitude, otherwise the baseline estimate below
    // (computed before real offsets are known) would drift for large files.
    const trailer =
      `trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${String(xrefOffset).padStart(10, "0")}\n%%EOF`;

    return concatBytes([
      header, commentBytes, ...objBytesList, textBytes(xref), textBytes(trailer),
    ]);
  }

  function xrefTrailerLength(objCount) {
    // "xref\n0 N\n" + (N+1) fixed 20-byte lines + trailer text (variable but we
    // measure it directly below), used only for the baseline estimate, so we
    // build the real xref/trailer once size is known; this helper just gives
    // an upper-bound-safe estimate by constructing the same strings.
    const xrefHeader = `xref\n0 ${objCount + 1}\n`;
    const lines = "0000000000 65535 f \n" + "0000000000 00000 n \n".repeat(objCount);
    const trailer = `trailer\n<< /Size ${objCount + 1} /Root 1 0 R >>\nstartxref\n0000000000\n%%EOF`;
    return textBytes(xrefHeader).length + textBytes(lines).length + textBytes(trailer).length;
  }

  // ---------- ZIP ----------
  function generateZip(size, filename = "padding.bin") {
    const nameBytes = textBytes(filename);
    const fixedOverhead = 30 + nameBytes.length + 46 + nameBytes.length + 22;
    const dataLen = Math.max(0, size - fixedOverhead);
    const data = randomBytes(dataLen, "blank"); // zero-filled so it compresses to nothing meaningful either way
    const crc = crc32Final(data);

    const modTime = u16le(0x0000);
    const modDate = u16le(0x0021); // arbitrary valid MS-DOS date

    const localHeader = concatBytes([
      u32le(0x04034b50),
      u16le(20), u16le(0), u16le(0),
      modTime, modDate,
      u32le(crc), u32le(dataLen), u32le(dataLen),
      u16le(nameBytes.length), u16le(0),
      nameBytes,
    ]);

    const centralHeader = concatBytes([
      u32le(0x02014b50),
      u16le(20), u16le(20), u16le(0), u16le(0),
      modTime, modDate,
      u32le(crc), u32le(dataLen), u32le(dataLen),
      u16le(nameBytes.length), u16le(0), u16le(0),
      u16le(0), u16le(0), u32le(0),
      u32le(0), // local header offset
      nameBytes,
    ]);

    const eocd = concatBytes([
      u32le(0x06054b50),
      u16le(0), u16le(0),
      u16le(1), u16le(1),
      u32le(centralHeader.length),
      u32le(localHeader.length + dataLen),
      u16le(0),
    ]);

    return concatBytes([localHeader, data, centralHeader, eocd]);
  }

  // ---------- GIF (1x1 base + Comment Extension padding) ----------
  const GIF_BASE_B64 = "R0lGODlhAQABAIAAAAAAAP///ywAAAAAAQABAAACAUwAOw==";

  function padGif(target) {
    const base = b64decode(GIF_BASE_B64); // ends in 0x3B trailer
    const trailer = base.subarray(base.length - 1);
    const body = base.subarray(0, base.length - 1);
    const need = target - base.length;
    if (need <= 0) return base;

    const R = need - 3; // 3 = extension introducer(2) + terminator(1)
    if (R < 0) return base; // can't pad below +3 bytes; caller reads back actual size

    const subblocks = [];
    let remaining = R;
    while (remaining > 256) {
      subblocks.push(255);
      remaining -= 256;
    }
    if (remaining === 1 && subblocks.length > 0) {
      subblocks[subblocks.length - 1] -= 1;
      remaining = 2;
    }
    if (remaining >= 2) {
      subblocks.push(remaining - 1);
    } // remaining === 0 or unrecoverable remaining === 1 (R<3 case) -> skip, off by <=1 byte

    const parts = [body, new Uint8Array([0x21, 0xFE])];
    for (const len of subblocks) {
      parts.push(new Uint8Array([len]));
      parts.push(randomBytes(len, "blank"));
    }
    parts.push(new Uint8Array([0x00])); // block terminator
    parts.push(trailer);
    return concatBytes(parts);
  }

  // ---------- JPEG padding (insert COM segments after SOI) ----------
  function padJpeg(baseBytes, target) {
    const need = target - baseBytes.length;
    if (need <= 0) return baseBytes;

    const segments = [];
    let remaining = need;
    while (remaining >= 4) {
      const dataLen = Math.min(65533, remaining - 4);
      segments.push(dataLen);
      remaining -= (4 + dataLen);
    }
    // remaining < 4 leftover is unpaddable at COM-segment granularity; the
    // caller reads back the real blob size rather than assuming exactness.

    const parts = [baseBytes.subarray(0, 2)]; // SOI
    for (const dataLen of segments) {
      parts.push(new Uint8Array([0xFF, 0xFE]));
      parts.push(u16be(dataLen + 2));
      parts.push(randomBytes(dataLen, "blank"));
    }
    parts.push(baseBytes.subarray(2));
    return concatBytes(parts);
  }

  // ---------- PNG padding (custom ancillary chunk before IEND) ----------
  function padPng(baseBytes, target) {
    const need = target - baseBytes.length;
    if (need <= 12) return baseBytes; // below chunk-overhead minimum

    const dataLen = need - 12;
    const type = textBytes("myPd"); // lowercase-first = ancillary, safely skippable
    const data = randomBytes(dataLen, "blank");
    const crcBytes = u32be(crc32Final(concatBytes([type, data])));
    const chunk = concatBytes([u32be(dataLen), type, data, crcBytes]);

    // IEND is always the final 12 bytes of a well-formed PNG.
    const head = baseBytes.subarray(0, baseBytes.length - 12);
    const iend = baseBytes.subarray(baseBytes.length - 12);
    return concatBytes([head, chunk, iend]);
  }

  const api = {
    generateTxt, generateBin, generatePdf, generateZip,
    GIF_BASE_B64, padGif, padJpeg, padPng, b64decode,
  };

  if (isNode) module.exports = api;
  else Object.assign(root, api);
})(typeof window !== "undefined" ? window : globalThis);
